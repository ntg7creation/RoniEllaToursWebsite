  await trip.waitFor(); assert.equal((await fetch(origin + path)).status, 404);
  await trip.getByRole('button', { name: 'פרטי הטיול' }).click();
  const details = page.locator('dialog.admin-workspace');
  await details.getByLabel('תקציר לכרטיסי הטיול').fill('תקציר מעודכן מהעורך');
