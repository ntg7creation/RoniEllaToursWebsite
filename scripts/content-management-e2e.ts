  await dialog.getByLabel(editorLabel('טקסט')).first().fill('טקסט הטיול שנשמר דרך הדפדפן');
  await dialog.getByRole('button', { name: 'הוספת פסקה' }).click();
  await dialog.getByLabel(editorLabel('טקסט')).last().fill('תנאי טיול חדשים שנשמרו');
  await dialog.getByRole('button', { name: 'שמירת תוכן העמוד' }).click();
  await dialog.getByText(editorLabel('השינויים נשמרו.')).waitFor();
  await dialog.getByRole('button', { name: 'סגירה ×' }).click();
