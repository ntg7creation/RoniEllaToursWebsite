  assert.equal((await fetch(origin + path)).status, 404);
  for (const listing of ['/', '/tours/']) assert.ok(!(await (await fetch(origin + listing)).text()).includes(`href="${path}"`));
  await trip.getByRole('button', { name: editorLabel('פרסום באתר') }).click();
  await dialog.getByRole('button', { name: 'אישור פרסום' }).click();
