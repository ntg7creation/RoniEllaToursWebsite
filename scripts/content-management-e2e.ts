  await details.getByText('השינויים נשמרו.').waitFor();
  await details.getByRole('button',{name:/SEO and topics/}).click();
  await details.getByRole('columnheader', { name: /Content/ }).waitFor();
  assert.equal(await details.locator('thead th').count(),3);
